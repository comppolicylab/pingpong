export function getLectureConversationStarters(
	languageCode?: string | null
): LectureConversationStarters {
	const code = languageCode?.trim().toLowerCase().split(/[-_]/)[0] ?? 'en';
	return Object.hasOwn(LECTURE_CONVERSATION_STARTERS, code)
		? LECTURE_CONVERSATION_STARTERS[code]
		: LECTURE_CONVERSATION_STARTERS.en;
}
